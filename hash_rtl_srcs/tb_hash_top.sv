`timescale 1ns/1ps

// Single-packet integration test for:
//   hash_top -> hash_values (FNV-1a, XOR-Shift, Toeplitz)
//            -> hash_mapping -> flow_table_bram
//
// Reset is active-low in the supplied RTL: rst=0 resets the design.
//
// Test scenario:
//   1. Send exactly one packet/flow.
//   2. Wait for the three hashes.
//   3. Pre-fill hash1 and hash2 candidate addresses with different flows.
//   4. Leave hash3 candidate address empty.
//   5. Verify the mapping FSM falls through to hash3 and stores the packet.
//
// Compile (Icarus Verilog):
//   iverilog -g2012 -s tb_hash_top -o simv \
//     tb_hash_top.sv hash_top.sv hashing.sv fnv_xor_pip.sv \
//     hash_mapping.sv bram.sv
// Run:
//   vvp simv

module tb_hash_top;

    localparam integer KEY_BITS  = 104;
    localparam integer TIME_BITS = 64;
    localparam integer TABLE_SIZE = 8192;

    reg clk = 1'b0;
    reg rst = 1'b0;
    reg valid = 1'b0;
    reg [KEY_BITS+TIME_BITS-1:0] key = '0;

    // The supplied hash_top does not expose done/hashes as top-level ports,
    // so this testbench observes its internal signals hierarchically.
    hash_top #(
        .KEY_BITS(KEY_BITS),
        .TIMESTAMP(TIME_BITS)
    ) dut (
        .clk   (clk),
        .rst   (rst),
        .valid (valid),
        .key   (key)
    );

    always #5 clk = ~clk;

    reg [KEY_BITS-1:0] packet_flow;
    reg [TIME_BITS-1:0] packet_timestamp;
    reg [KEY_BITS-1:0] fake_flow_1;
    reg [KEY_BITS-1:0] fake_flow_2;
    integer i;
    integer addr1, addr2, addr3;
    integer cycles;

    initial begin
        packet_flow      = 104'h0123456789ABCDEFFEDCBA9876;
        packet_timestamp = 64'h0000000000001234;
        fake_flow_1      = 104'h11111111111111111111111111;
        fake_flow_2      = 104'h22222222222222222222222222;

        // Initialize every BRAM word because the RTL BRAM has no reset/
        // initialization loop. Entry layout is {occupied, flow_key, timestamp}.
        for (i = 0; i < TABLE_SIZE; i = i + 1)
            dut.u_hash_mapping.u_flow_table_bram.mem[i] = '0;

        // Hold reset for several clock edges. rst is active-low.
        repeat (4) @(negedge clk);
        rst = 1'b1;
        repeat (2) @(negedge clk);

        $display("\n[TB] Sending one packet...");
        key   = {packet_timestamp, packet_flow};
        valid = 1'b1;
        @(negedge clk);
        valid = 1'b0;
        key   = '0;

        // Wait for the hash pipeline to finish. The output pulse and hash
        // values are generated by hash_values.
        cycles = 0;
        while (dut.u_hash_values.valid_out !== 1'b1 && cycles < 100) begin
            @(posedge clk);
            #1;
            cycles = cycles + 1;
        end

        if (dut.u_hash_values.valid_out !== 1'b1) begin
            $fatal(1, "[FAIL] Hash pipeline did not assert valid_out.");
        end

        // Use the actual computed hashes to determine the three BRAM addresses.
        addr1 = dut.u_hash_values.hash1[12:0];
        addr2 = dut.u_hash_values.hash2[12:0];
        addr3 = dut.u_hash_values.hash3[12:0];

        $display("[TB] Hash pipeline completed after %0d observed cycles.", cycles);
        $display("[TB] FNV-1a   = 0x%08h -> address %0d",
                 dut.u_hash_values.hash1, addr1);
        $display("[TB] XOR-Shift= 0x%08h -> address %0d",
                 dut.u_hash_values.hash2, addr2);
        $display("[TB] Toeplitz = 0x%08h -> address %0d",
                 dut.u_hash_values.hash3, addr3);

        if ((addr1 == addr2) || (addr1 == addr3) || (addr2 == addr3)) begin
            $fatal(1,
                "[FAIL] Candidate addresses are not distinct (%0d, %0d, %0d). Use another packet key for this scenario.",
                addr1, addr2, addr3);
        end

        // Simulate two occupied candidate buckets belonging to other flows.
        // The third candidate is deliberately left empty.
        dut.u_hash_mapping.u_flow_table_bram.mem[addr1] =
            {1'b1, fake_flow_1, 64'h0000000000000100};
        dut.u_hash_mapping.u_flow_table_bram.mem[addr2] =
            {1'b1, fake_flow_2, 64'h0000000000000200};

        if (dut.u_hash_mapping.u_flow_table_bram.mem[addr3][168] !== 1'b0)
            $fatal(1, "[FAIL] Third candidate address was expected to be empty.");

        $display("[TB] Pre-filled address %0d (hash1) with a different flow.", addr1);
        $display("[TB] Pre-filled address %0d (hash2) with a different flow.", addr2);
        $display("[TB] Left address %0d (hash3) empty.", addr3);

        // The mapping block receives the hash valid pulse on a subsequent
        // clock edge. Wait for its done pulse with a timeout.
        cycles = 0;
        while (dut.done !== 1'b1 && cycles < 100) begin
            @(posedge clk);
            #1;
            cycles = cycles + 1;
        end

        if (dut.done !== 1'b1)
            $fatal(1, "[FAIL] Mapping FSM did not assert done.");

        $display("[TB] Mapping asserted done.");

        // Check that the first two occupied entries were not overwritten.
        if (dut.u_hash_mapping.u_flow_table_bram.mem[addr1][168] !== 1'b1 ||
            dut.u_hash_mapping.u_flow_table_bram.mem[addr1][167:64] !== fake_flow_1)
            $fatal(1, "[FAIL] Hash1 collision entry was unexpectedly changed.");

        if (dut.u_hash_mapping.u_flow_table_bram.mem[addr2][168] !== 1'b1 ||
            dut.u_hash_mapping.u_flow_table_bram.mem[addr2][167:64] !== fake_flow_2)
            $fatal(1, "[FAIL] Hash2 collision entry was unexpectedly changed.");

        // The packet should be placed at hash3 because hash1 and hash2 collided.
        if (dut.u_hash_mapping.u_flow_table_bram.mem[addr3][168] !== 1'b1)
            $fatal(1, "[FAIL] Hash3 entry was not marked occupied.");

        if (dut.u_hash_mapping.u_flow_table_bram.mem[addr3][167:64] !== packet_flow)
            $fatal(1, "[FAIL] Stored flow key at hash3 does not match input packet.");

        if (dut.u_hash_mapping.u_flow_table_bram.mem[addr3][63:0] !== packet_timestamp)
            $fatal(1, "[FAIL] Stored timestamp at hash3 does not match input packet.");

        $display("\n[PASS] Single-packet three-hash fallback test passed.");
        $display("[PASS] hash1 collided; hash2 collided; hash3 was selected.");
        $display("[PASS] BRAM contains the correct 104-bit flow key and 64-bit timestamp.");
        $finish;
    end

    // Global watchdog protects against a stuck FSM/pipeline.
    initial begin
        #5000;
        $fatal(1, "[FAIL] Global simulation timeout.");
    end

endmodule
